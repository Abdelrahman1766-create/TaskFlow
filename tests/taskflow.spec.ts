import { expect, test } from '@playwright/test'

test('core task actions persist across reloads', async ({ page }) => {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  const composer = page.getByRole('textbox', { name: 'What needs your attention?' })
  await composer.fill('  Submit assignment  ')
  await composer.press('Enter')
  await expect(page.getByText('Submit assignment', { exact: true })).toBeVisible()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByText('Submit assignment', { exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Edit task: Submit assignment' }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Edit task: Submit assignment' })).toBeFocused()
  await page.getByRole('button', { name: 'Edit task: Submit assignment' }).click()
  await page.locator('#edit-task-title').fill('Submit polished assignment')
  await page.getByRole('button', { name: 'SAVE CHANGES' }).click()
  await expect(page.getByText('Submit polished assignment', { exact: true })).toBeVisible()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: 'COMPLETE: Submit polished assignment' }).click()
  await expect(page.getByRole('button', { name: 'IN PROGRESS: Submit polished assignment' })).toHaveAttribute('aria-pressed', 'true')
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('button', { name: 'IN PROGRESS: Submit polished assignment' })).toBeVisible()

  await page.getByRole('button', { name: 'Delete task: Submit polished assignment' }).click()
  await expect(page.getByText('Submit polished assignment', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'UNDO' }).click()
  await expect(page.getByText('Submit polished assignment', { exact: true })).toBeVisible()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByText('Submit polished assignment', { exact: true })).toBeVisible()
})

test('details, search, filters, calendar, and confirmation', async ({ page }) => {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  const due = new Date()
  due.setMonth(due.getMonth() + 1, 12)
  const dueValue = `${due.getFullYear()}-${String(due.getMonth() + 1).padStart(2, '0')}-12`
  await page.getByRole('textbox', { name: 'What needs your attention?' }).fill('Prepare slides')
  await page.getByRole('button', { name: 'DETAILS' }).click()
  await page.getByRole('textbox', { name: 'DESCRIPTION' }).fill('For the interview')
  await page.getByRole('textbox', { name: 'CATEGORY' }).fill('Work')
  await page.getByRole('textbox', { name: 'DUE DATE' }).fill(dueValue)
  await page.getByRole('combobox', { name: 'PRIORITY', exact: true }).selectOption('high')
  await page.getByRole('button', { name: 'Add task' }).click()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByText('Prepare slides', { exact: true })).toBeVisible()
  await expect(page.getByText('For the interview')).toBeVisible()
  await page.getByRole('searchbox', { name: 'Search tasks…' }).fill('missing')
  await expect(page.getByText('No matches.')).toBeVisible()
  await page.getByRole('searchbox', { name: 'Search tasks…' }).fill('slides')
  await expect(page.getByText('Prepare slides', { exact: true })).toBeVisible()
  await page.getByRole('searchbox', { name: 'Search tasks…' }).fill('')
  await page.getByRole('button', { name: /COMPLETED/ }).first().click()
  await expect(page.getByText('No tasks in this view right now.')).toBeVisible()
  await page.getByRole('button', { name: /ALL/ }).first().click()
  await page.getByRole('button', { name: 'CALENDAR' }).click()
  await page.getByRole('button', { name: 'Next month' }).click()
  await expect(page.getByRole('heading', { name: new Intl.DateTimeFormat('en-US', { month: 'long', year: 'numeric' }).format(due) })).toBeVisible()
  await page.getByRole('gridcell', { name: new RegExp(`${due.getMonth() + 1}/12/${due.getFullYear()}`) }).click()
  await expect(page.getByText('Prepare slides', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'LIST' }).click()
  await page.getByRole('button', { name: 'COMPLETE: Prepare slides' }).click()
  await page.getByRole('button', { name: /CLEAR FINISHED/ }).click()
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.getByRole('button', { name: 'CANCEL' }).click()
  await expect(page.getByText('Prepare slides', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /CLEAR FINISHED/ })).toBeFocused()
  await page.getByRole('button', { name: /CLEAR FINISHED/ }).click()
  await page.getByRole('button', { name: 'CLEAR TASKS' }).click()
  await expect(page.getByText('Prepare slides', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'What needs your attention?' })).toBeFocused()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByText('Prepare slides', { exact: true })).toHaveCount(0)
})

test('validation, keyboard shortcut, and corrupted saved data', async ({ page }) => {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await page.getByRole('textbox', { name: 'What needs your attention?' }).press('Enter')
  await expect(page.getByRole('alert')).toContainText('Give your task a title')
  await page.getByRole('textbox', { name: 'What needs your attention?' }).fill('   ')
  await page.getByRole('textbox', { name: 'What needs your attention?' }).press('Enter')
  await expect(page.getByText('Room to begin.')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.keyboard.press('/')
  await expect(page.getByRole('textbox', { name: 'What needs your attention?' })).toBeFocused()
  await page.evaluate(() => localStorage.setItem('taskflow.tasks.v1', '{invalid'))
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('status').filter({ hasText: 'Some saved tasks could not be loaded' })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('taskflow.tasks.invalid-backup'))).toBe('{invalid')
})

test('legacy and partly invalid saved tasks recover without startup overwrite', async ({ page }) => {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  const saved = JSON.stringify([
    { id: 'old-1', text: 'Legacy task', createdAt: Date.now(), completed: false },
    { id: 'broken', title: '', createdAt: 0, completed: false },
  ])
  await page.evaluate(value => localStorage.setItem('taskflow.tasks.v1', value), saved)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByText('Legacy task', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('taskflow.tasks.v1'))).toBe(saved)
  expect(await page.evaluate(() => localStorage.getItem('taskflow.tasks.invalid-backup'))).toBe(saved)
  await page.getByRole('button', { name: 'COMPLETE: Legacy task' }).click()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('button', { name: 'IN PROGRESS: Legacy task' })).toBeVisible()
})

test('language, theme, and viewport layouts persist', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await page.getByRole('combobox', { name: 'Language' }).selectOption('ru')
  await page.getByRole('button', { name: 'Включить тёмную тему' }).click()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.locator('html')).toHaveAttribute('lang', 'ru')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.getByRole('heading', { name: /Освободите место/ })).toBeVisible()
  await page.waitForTimeout(900)
  for (const width of [320, 375, 390, 768, 1024, 1440, 1920]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `horizontal overflow at ${width}px`).toBeTruthy()
    if ([320, 768, 1440].includes(width)) {
      await page.screenshot({ path: testInfo.outputPath(`ru-dark-${width}.png`), fullPage: true, animations: 'disabled' })
    }
  }
  expect(errors).toEqual([])
})

test('long titles, quick interactions, sorting, and light layouts', async ({ page }, testInfo) => {
  test.setTimeout(60_000)
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  const composer = page.getByRole('textbox', { name: 'What needs your attention?' })
  const longTitle = 'Review '.repeat(30).slice(0, 230)
  await composer.fill(longTitle)
  await composer.press('Enter')
  await composer.fill('Urgent interview task')
  await page.getByRole('button', { name: 'DETAILS' }).click()
  await page.getByRole('combobox', { name: 'PRIORITY', exact: true }).selectOption('high')
  await page.getByRole('textbox', { name: 'CATEGORY' }).fill('Work')
  await composer.press('Enter')
  await page.getByRole('combobox', { name: 'SORT BY' }).selectOption('priority')
  await expect(page.getByRole('listitem').first()).toContainText('Urgent interview task')
  await page.getByRole('combobox', { name: 'CATEGORY', exact: true }).selectOption('Work')
  await expect(page.getByRole('listitem')).toHaveCount(1)
  await page.getByRole('combobox', { name: 'CATEGORY', exact: true }).selectOption('all')
  const check = page.getByRole('button', { name: 'COMPLETE: Urgent interview task' })
  await check.click()
  await page.getByRole('button', { name: 'IN PROGRESS: Urgent interview task' }).click()
  await expect(check).toHaveAttribute('aria-pressed', 'false')
  for (const width of [320, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `horizontal overflow at ${width}px`).toBeTruthy()
    await page.screenshot({ path: testInfo.outputPath(`en-light-${width}.png`), fullPage: true, animations: 'disabled' })
  }
  await page.getByRole('combobox', { name: 'Language' }).selectOption('ru')
  await page.getByRole('button', { name: 'Включить тёмную тему' }).click()
  await page.setViewportSize({ width: 320, height: 900 })
  await page.screenshot({ path: testInfo.outputPath('ru-dark-populated-320.png'), fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Изменить задачу: Urgent interview task' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('ru-dark-dialog-320.png'), fullPage: true, animations: 'disabled' })
})
